/**
 * Emits src/generated/not-modeled.ts: every laboratory manifest's `notModeled` list
 * (content/experiments/<id>.yaml), keyed by laboratory id (am-rc1001-bridge-plan-pcjk.26).
 *
 * WHY. AGENTS.md says the manifest's notModeled is "shown as a plain line; an empty list fails the
 * audit", and src/testing/notModeledVisible.test.tsx holds every built lab page to its manifest
 * (33 manifests, 210 items, 210 shown). The reader-facing half is therefore done. What this closes
 * is the other half of the bead: 22 `src/experiments/<id>/definition.ts` modules each keep their own
 * NOT_MODELED copy, so the manifest the audit checks is not the array the component renders -- two
 * sources for one thing, agreeing only because a test makes them.
 *
 * THE MIGRATION IS PRICED, measured 2026-10-09 and again here: of the 22 constants, 19 are
 * byte-identical to their manifest, 2 (lq-03 and sr-04) differ only in letter case, and lq-09
 * differs only by a trailing full stop on each of its six items. Zero differ in content or order.
 * So pointing them here is invisible to a reader except that two labs gain a leading capital and
 * lq-09 gains six full stops, and in each case the manifest is the authority, which makes those
 * corrections rather than regressions.
 *
 * A .ts module, not JSON, for the reason generate-model-domains.mjs gives beside it:
 * generate-tracers.mjs and its siblings hash each evaluator's import closure and refuse any
 * dependency that is not .ts or .mjs ("Unhashable evaluator dependency").
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { strictParse } from "../src/content/schemas/strictParse.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifests = resolve(root, "content/experiments");
const out = resolve(root, "src/generated/not-modeled.ts");

export async function generateNotModeled() {
  const labs = {};
  let items = 0;
  for (const file of (await readdir(manifests)).filter((f) => f.endsWith(".yaml")).sort()) {
    const id = file.slice(0, -".yaml".length);
    const manifest = strictParse(await readFile(resolve(manifests, file), "utf8"), "yaml");
    const list = manifest.notModeled;
    // An empty or absent list is a manifest defect the instrument audit already refuses; this
    // generator refuses it too rather than emitting an empty array that a component would render as
    // a blank line.
    if (!Array.isArray(list) || list.length === 0)
      throw new TypeError(
        `content/experiments/${file}: notModeled must be a non-empty list of strings, not ${JSON.stringify(list)}`,
      );
    labs[id] = list.map((entry, i) => {
      if (typeof entry !== "string" || entry.trim() === "")
        throw new TypeError(
          `content/experiments/${file}: notModeled[${i}] must be a non-empty string, not ${JSON.stringify(entry)}`,
        );
      return entry.trim();
    });
    items += labs[id].length;
  }
  const text = `// Generated by scripts/generate-not-modeled.mjs from content/experiments/*.yaml. Do not edit.
//
// What each laboratory's model leaves out, as its manifest declares it. The manifest is the one
// place these sentences are written; a component renders this array rather than its own copy
// (am-rc1001-bridge-plan-pcjk.26).
//
// DATA ONLY. The lookup and its typed refusal live in src/experiments/notModeled.ts, because a
// refusal in a generated file cannot be given a tested code: the bare-throw ratchet reported this
// module as undeclared debt the first time it carried one, and a generated file is the wrong place
// to baseline a debt or to write a test against.
export const NOT_MODELED: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(labs, null, 2)};
`;
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, text);
  return { labs: Object.keys(labs).length, items };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { labs, items } = await generateNotModeled();
  console.log(JSON.stringify({ event: "not-modeled-generated", labs, items }));
}
