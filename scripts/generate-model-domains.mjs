/**
 * Emits src/generated/model-domains.ts: every numeric modelDomain the laboratory manifests
 * declare (content/experiments/<id>.yaml), keyed by laboratory id and parameter id (dispatch 134).
 *
 * The lab validators refuse a setting outside it through src/experiments/controls/declaredDomain.ts,
 * so the manifest is the one place a range is written. BM-01 accepted T = 1e300 K beside a manifest
 * declaring 273-330 K because nothing read the manifest at run time.
 *
 * Values are in the parameter's own stored units, as the manifests write them. A reason's trailing
 * source-file note, such as "(src/experiments/bm01/parameters.ts)", is for authors and is dropped.
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { strictParse } from "../src/content/schemas/strictParse.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifests = resolve(root, "content/experiments");
// A .ts module, not JSON: generate-tracers.mjs and its siblings hash each evaluator's import closure
// and refuse any dependency that is not .ts or .mjs ("Unhashable evaluator dependency").
const out = resolve(root, "src/generated/model-domains.ts");

const bound = (value, where) => {
  if (value === undefined) return undefined;
  if (typeof value !== "number" || !Number.isFinite(value))
    throw new TypeError(`${where}: a modelDomain bound must be a finite number, not ${value}`);
  return value;
};

export async function generateModelDomains() {
  const labs = {};
  for (const file of (await readdir(manifests)).filter((f) => f.endsWith(".yaml")).sort()) {
    const id = file.slice(0, -".yaml".length);
    const manifest = strictParse(await readFile(resolve(manifests, file), "utf8"), "yaml");
    const domains = {};
    for (const p of manifest.parameters ?? []) {
      const d = p.modelDomain;
      if (!d || (typeof d.min !== "number" && typeof d.max !== "number")) continue;
      const where = `content/experiments/${file} ${p.id}`;
      domains[p.id] = {
        label: p.label,
        displayUnit: p.displayUnit ?? "",
        ...(d.min === undefined
          ? {}
          : { min: bound(d.min, where), minInclusive: d.minInclusive !== false }),
        ...(d.max === undefined
          ? {}
          : { max: bound(d.max, where), maxInclusive: d.maxInclusive !== false }),
        reason: String(d.reason ?? "").replace(/\s*\((?:src|scripts)\/[^)]*\)\s*$/, ""),
      };
    }
    if (Object.keys(domains).length > 0) labs[id] = domains;
  }
  const text = `// Generated by scripts/generate-model-domains.mjs from content/experiments/*.yaml. Do not edit.
export type GeneratedModelDomain = Readonly<{
  label: string;
  displayUnit: string;
  min?: number;
  minInclusive?: boolean;
  max?: number;
  maxInclusive?: boolean;
  reason: string;
}>;

export const MODEL_DOMAINS: Readonly<Record<string, Readonly<Record<string, GeneratedModelDomain>>>> = ${JSON.stringify(labs, null, 2)};
`;
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, text);
  return {
    labs: Object.keys(labs).length,
    domains: Object.values(labs).reduce((n, d) => n + Object.keys(d).length, 0),
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { labs, domains } = await generateModelDomains();
  console.log(JSON.stringify({ event: "model-domains-generated", labs, domains }));
}
