/**
 * Emits the pre-paint storage key constants from the registry, so an inline pre-paint script and
 * the module that later reads the same setting can never spell a key differently. The emitted
 * set is exactly the settings registered with `prePaint: true` — computed from the registry,
 * never a second hand-maintained list.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import {
  type KeyRegistry,
  type SettingRegistration,
  storageKeyRegistry,
} from "../../src/platform/storage/keys.ts";

/** `am:settings:v1:paragraphSpacing` -> `STORAGE_KEY_PARAGRAPH_SPACING`. */
export function constantNameFor(settingKey: string): string {
  const suffix = settingKey.split(":").at(-1);
  if (!suffix) throw new Error(`Malformed setting key "${settingKey}".`);
  const snake = suffix.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
  return `STORAGE_KEY_${snake}`;
}

export const GENERATED_FILE_HEADER =
  "// Generated by scripts/build/injectStorageKeys.ts. Do not hand-edit.\n";

/**
 * Fails naming any pre-paint setting the caller's `emittedConstantNames` does not include, so a
 * registry entry marked `prePaint: true` can never silently fall out of the injected set.
 */
export function assertEveryPrePaintKeyIsEmitted(
  registry: KeyRegistry,
  emittedConstantNames: ReadonlySet<string>,
): void {
  for (const entry of registry.prePaintSettings()) {
    const name = constantNameFor(entry.key);
    if (!emittedConstantNames.has(name)) {
      throw new Error(
        `Pre-paint setting "${entry.key}" (expected constant ${name}) is missing from the injected key set.`,
      );
    }
  }
}

/** Pure: produces the generated source text from the registry's current pre-paint settings. */
export function generatePrePaintKeyModule(registry: KeyRegistry = storageKeyRegistry): string {
  const settings: readonly SettingRegistration[] = [...registry.prePaintSettings()].sort((a, b) =>
    a.key.localeCompare(b.key),
  );
  const emitted = new Set(settings.map((entry) => constantNameFor(entry.key)));
  assertEveryPrePaintKeyIsEmitted(registry, emitted);
  const lines = settings.map(
    (entry) => `export const ${constantNameFor(entry.key)} = ${JSON.stringify(entry.key)};`,
  );
  return `${GENERATED_FILE_HEADER}${lines.join("\n")}\n`;
}

export const GENERATED_OUTPUT_PATH = path.join("generated", "storage", "prePaintKeys.ts");

function main(): void {
  const source = generatePrePaintKeyModule();
  const target = path.join(process.cwd(), GENERATED_OUTPUT_PATH);
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, source, "utf8");
  console.log(
    `Wrote ${GENERATED_OUTPUT_PATH} (${storageKeyRegistry.prePaintSettings().length} pre-paint keys).`,
  );
}

const isMainModule =
  process.argv[1] !== undefined && import.meta.url === `file://${process.argv[1]}`;
if (isMainModule) main();
