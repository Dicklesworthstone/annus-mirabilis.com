/**
 * Emits src/generated/predict-prompts.ts: each laboratory's predict prompts, read from its manifest
 * (content/experiments/<id>.yaml), for the predict panel to draw (am-inst-predict-mode-ti7m).
 *
 * The manifest is the one place a prompt is written. Until this, a lab that asked for a prediction
 * kept its own TypeScript copy of the question and candidates (ME02_PREDICT_PROMPT,
 * SR01_PREDICT_MOVING_PAIR), and dispatch 141 counted 0 of 33 laboratories that hid their result
 * until the reader had predicted.
 *
 * Each prompt carries the candidate the model supports (supportedCandidateId), which the panel needs
 * to say how the reader's choice compares with the result. A prompt without one fails the run. A lab
 * whose manifest records a predict-mode exemption is listed with its reason, so every manifest lands
 * in exactly one of the two tables.
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateExperiment } from "../src/content/schemas/experiment.ts";
import { strictParse } from "../src/content/schemas/strictParse.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifests = resolve(root, "content/experiments");
// A .ts module, not JSON, as src/generated/model-domains.ts is: the evaluator-closure hashers in
// generate-tracers.mjs and its siblings refuse any dependency that is not .ts or .mjs.
const out = resolve(root, "src/generated/predict-prompts.ts");

/**
 * The prompts and exemptions in a set of manifests, each given as its file name and text. Pure, so a
 * test can run it on the real directory or on a manifest it has altered in memory.
 */
export function predictPromptsFrom(files) {
  const prompts = {};
  const exempt = {};
  for (const { file, text } of [...files].sort((a, b) => a.file.localeCompare(b.file))) {
    const manifest = validateExperiment(strictParse(text, "yaml"));
    const mode = manifest.predictMode;
    if ("exempt" in mode) {
      exempt[manifest.id] = mode.reason;
      continue;
    }
    prompts[manifest.id] = mode.prompts.map((p) => {
      if (typeof p.supportedCandidateId !== "string") {
        throw new TypeError(
          `content/experiments/${file}: predict prompt "${p.promptId}" names no supportedCandidateId, so the panel could not say how a reader's prediction compares with the result.`,
        );
      }
      return {
        promptId: p.promptId,
        ...(p.controlId ? { controlId: p.controlId } : {}),
        ...(p.actionId ? { actionId: p.actionId } : {}),
        question: p.question,
        supportedCandidateId: p.supportedCandidateId,
        candidates: p.candidates.map((c) => ({
          id: c.id,
          label: c.label,
          description: c.description,
          separatingAssumption: c.separatingAssumption,
        })),
      };
    });
  }
  return { prompts, exempt };
}

/** The module text for a result of predictPromptsFrom. */
export function predictPromptsModule({ prompts, exempt }) {
  return `// Generated by scripts/generate-predict-prompts.mjs from content/experiments/*.yaml. Do not edit.
export type GeneratedPredictCandidate = Readonly<{
  id: string;
  label: string;
  description: string;
  separatingAssumption: string;
}>;

export type GeneratedPredictPrompt = Readonly<{
  promptId: string;
  controlId?: string;
  actionId?: string;
  question: string;
  supportedCandidateId: string;
  candidates: readonly GeneratedPredictCandidate[];
}>;

/** Each laboratory's predict prompts, in manifest order. */
export const PREDICT_PROMPTS: Readonly<Record<string, readonly GeneratedPredictPrompt[]>> = ${JSON.stringify(prompts, null, 2)};

/** Laboratories whose manifest records a predict-mode exemption, with its reason. */
export const PREDICT_EXEMPTIONS: Readonly<Record<string, string>> = ${JSON.stringify(exempt, null, 2)};
`;
}

export async function generatePredictPrompts() {
  const files = [];
  for (const file of (await readdir(manifests)).filter((f) => f.endsWith(".yaml")).sort()) {
    files.push({ file, text: await readFile(resolve(manifests, file), "utf8") });
  }
  const result = predictPromptsFrom(files);
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, predictPromptsModule(result));
  return {
    manifests: files.length,
    labs: Object.keys(result.prompts).length,
    prompts: Object.values(result.prompts).reduce((n, list) => n + list.length, 0),
    exempt: Object.keys(result.exempt).length,
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(
    JSON.stringify({ event: "predict-prompts-generated", ...(await generatePredictPrompts()) }),
  );
}
